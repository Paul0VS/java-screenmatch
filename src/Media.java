public class Media {
    public static void main(String[] args) {

        double nota1 = 7.9;
        double nota2 = 10;
        double media1 = (nota1) /2;
        double media2 = (nota2) /2;
        double mediaFinal = (nota1 + nota2) /2;

        System.out.println("Aluno 1 : Paulo Vinícius | Nota : " + nota1);
        System.out.println("Aluno 2 : Ana Claudia | Nota :  " + nota2);
        System.out.println("Media de Paulo : " + media1);
        System.out.println("Media de Ana : " + media2);
        System.out.println("Média dos dois alunos: " + mediaFinal);
    }
}
